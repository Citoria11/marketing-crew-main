"""SQLAlchemy models for the Country Music Band AI platform.

Defines one primary table:
- ``campaigns``: stores uploaded .mp3 metadata and agent-generated content.

LangGraph checkpoint state is managed directly by ``AsyncPostgresSaver``
(see ``workflow/config.py``) and lives in its own PostgreSQL tables.
"""

from __future__ import annotations

import uuid

from sqlalchemy import (
    JSON,
    Column,
    DateTime,
    String,
    Text,
    func,
)
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import DeclarativeBase


class Base(DeclarativeBase):
    """Shared declarative base for all ORM models."""


# ---------------------------------------------------------------------------
# Campaign – stores mp3 metadata and agent-generated content
# ---------------------------------------------------------------------------


class Campaign(Base):
    """One campaign ties together an uploaded track and all AI-generated content.

    A *campaign* is created when a producer uploads an .mp3 file.  The
    LangGraph workflow then populates the analysis / lore / social-media fields
    as each node completes.
    """

    __tablename__ = "campaigns"

    id: Column = Column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )

    # -----------------------------------------------------------------------
    # Audio metadata
    # -----------------------------------------------------------------------
    original_filename: Column = Column(
        String(512),
        nullable=True,
        comment="Original filename as uploaded by the user.",
    )
    # Relative or absolute path/key where the file is stored (local FS or S3).
    storage_path: Column = Column(
        String(1024),
        nullable=True,
        comment="Storage path or object-store key for the .mp3 file.",
    )
    duration_seconds: Column = Column(
        # Store as string to avoid precision issues; or use Numeric if preferred.
        String(32),
        nullable=True,
        comment="Duration of the audio file in seconds (float encoded as string).",
    )
    sample_rate: Column = Column(
        String(16),
        nullable=True,
        comment="Sample rate of the audio file in Hz.",
    )
    # BPM, key, and other librosa-derived metadata stored as free-form JSON.
    audio_analysis: Column = Column(
        JSON,
        nullable=True,
        default=None,
        comment=(
            "Librosa analysis results: BPM, spectral centroid, hook start/end, "
            "energy profile, etc."
        ),
    )

    # -----------------------------------------------------------------------
    # Agent-generated lore (LoreArchitect output)
    # -----------------------------------------------------------------------
    music_brief: Column = Column(
        Text,
        nullable=True,
        comment="Marketing brief generated by the MusicAnalyst agent.",
    )
    lore: Column = Column(
        Text,
        nullable=True,
        comment="Americana/Outlaw backstory and lore generated by the LoreArchitect agent.",
    )
    # Raw ChromaDB retrieval context stored for reproducibility / debugging.
    rag_context: Column = Column(
        JSON,
        nullable=True,
        comment="Top-k ChromaDB passages retrieved during lore generation.",
    )

    # -----------------------------------------------------------------------
    # Content Director output – social-media assets
    # -----------------------------------------------------------------------
    # List of proposal dicts, each with keys like 'platform', 'copy', 'hashtags'.
    social_media_proposals: Column = Column(
        JSON,
        nullable=True,
        default=list,
        comment="Array of social-media post proposals produced by ContentDirector.",
    )
    # Index of the proposal selected by the human reviewer (-1 = none yet).
    selected_proposal_index: Column = Column(
        String(8),
        nullable=True,
        default="-1",
        comment="Index into social_media_proposals chosen by the human reviewer.",
    )

    # -----------------------------------------------------------------------
    # LangGraph linkage
    # -----------------------------------------------------------------------
    thread_id: Column = Column(
        String(255),
        nullable=True,
        unique=True,
        index=True,
        comment="LangGraph thread_id for this campaign's workflow run.",
    )
    workflow_status: Column = Column(
        String(64),
        nullable=False,
        default="created",
        index=True,
        comment=(
            "High-level workflow status: created | chat | analyzing | brainstorming | "
            "awaiting_approval | producing | done | error."
        ),
    )

    # -----------------------------------------------------------------------
    # Timestamps
    # -----------------------------------------------------------------------
    created_at: Column = Column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )
    updated_at: Column = Column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )

    def __repr__(self) -> str:  # pragma: no cover
        return (
            f"<Campaign id={self.id!r} file={self.original_filename!r} "
            f"status={self.workflow_status!r}>"
        )
