"""ContentDirector LangGraph node.

Synthesises music_brief + lore into platform-specific social media proposals.
The platforms generated are determined by task_type in state.
Input:  state['music_brief'], state['lore'], state['task_type'], state['user_context']
Output: state['social_media_proposals']
"""
from __future__ import annotations

import logging

from pydantic import BaseModel

from agents.base import get_chat_model
from agents.content_director.prompts import SYSTEM_PROMPT, build_user_prompt
from workflow.state import WorkflowState

logger = logging.getLogger(__name__)


class Proposal(BaseModel):
    platform: str
    copy: str
    hashtags: list[str]
    hook_reference: str
    # Visual assets — generated by downstream nodes from these prompts
    visual_direction: str = ""
    """A detailed DALL-E 3 / Midjourney image prompt for a still to accompany this post."""
    video_concept: str = ""
    """A 30-60 second short-form video concept/outline (for Reels / TikTok)."""


class ContentDirectorOutput(BaseModel):
    proposals: list[Proposal]


async def run_content_director(state: WorkflowState) -> dict:
    """LangGraph node: produces platform-specific social media proposals."""
    model = get_chat_model(temperature=0.6).with_structured_output(ContentDirectorOutput)
    logger.info("content_director: generating proposals for task_type=%s", state.get("task_type", "unknown"))
    try:
        result: ContentDirectorOutput = await model.ainvoke(
            [
                {"role": "system", "content": SYSTEM_PROMPT},
                {
                    "role": "user",
                    "content": build_user_prompt(
                        music_brief=state.get("music_brief", ""),
                        lore=state.get("lore", ""),
                        audio_analysis_summary=state.get("audio_analysis_summary", ""),
                        task_type=state.get("task_type", "social_media_suite"),
                        user_context=state.get("user_context", {}),
                    ),
                },
            ]
        )
    except Exception as exc:
        logger.error("content_director LLM call failed: %s", exc, exc_info=True)
        raise

    proposals = [p.model_dump() for p in result.proposals]

    agents_completed = list(state.get("agents_completed", []))
    if "content_director" not in agents_completed:
        agents_completed.append("content_director")

    logger.info("content_director: %d proposals generated", len(proposals))
    return {
        "social_media_proposals": proposals,
        "agents_completed": agents_completed,
        "current_node": "content_director",
        "clarification_needed": "",
    }
